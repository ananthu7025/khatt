"""One-off: turn the finished desert-safari page into a template that every tour-category page is built from."""
import re, sys
src, out = sys.argv[1], sys.argv[2]
t = open(src).read()

def block(start, end, token, inclusive_end=True):
    """Replace text from `start` up to and including `end` (first occurrence after start) with token."""
    global t
    i = t.index(start); j = t.index(end, i) + (len(end) if inclusive_end else 0)
    t = t[:i] + token + t[j:]

def one(a, b):
    global t
    assert t.count(a) == 1, (t.count(a), a[:90]); t = t.replace(a, b)

# head
block('<title>', '</title>', '<title>{{TITLE}}</title>')
block('<meta name="description"', '>', '<meta name="description" content="{{DESC}}">')
block('<link rel="canonical"', '>', '<link rel="canonical" href="https://khattourism.com/{{SLUG}}/">')
block('<meta property="og:title"', '>', '<meta property="og:title" content="{{TITLE}}">')
block('<meta property="og:description"', '>', '<meta property="og:description" content="{{DESC}}">')
block('<meta property="og:url"', '>', '<meta property="og:url" content="https://khattourism.com/{{SLUG}}/">')
block('<meta property="og:image"', '>', '<meta property="og:image" content="https://khattourism.com/assets/img/{{HERO}}">')
block('<link rel="preload" as="image"', '>', '<link rel="preload" as="image" href="/assets/img/{{HERO}}" fetchpriority="high">')
block('<script type="application/ld+json">', '</script>', '<script type="application/ld+json">\n{{LD}}\n</script>')

# the data block and the note above it
block('<!--\n  Everything that changes lives in this block.', '-->', '<!--\n  Generated by _build/site/build.py from the page config there. Edit the config, not this file.\n-->')
block('<script type="application/json" id="safari-data">', '</script>', '<script type="application/json" id="safari-data">\n{{DATA}}\n</script>')

# shared header and footer
block('<header class="top">', '</header>', '{{HEADER}}')
block('<footer>', '</footer>', '{{FOOTER}}')

# page content
block('<nav class="crumbs"', '</nav>', '<nav class="crumbs" aria-label="Breadcrumb"><a href="/">Home</a> › {{CRUMB}}</nav>')
block('<h1>', '</h1>', '<h1>{{H1}}</h1>')
block('<p class="sub">', '</p>', '<p class="sub">{{SUB}}</p>')
block('<div class="gallery">', '<div class="layout">', '{{GALLERY}}\n\n  ', inclusive_end=False)
block('<ul class="facts">', '</ul>', '{{FACTS}}')
block('<h2 class="sec">Which safari is right for you?</h2>', '</p>', '<h2 class="sec">{{OPT_TITLE}}</h2>\n        <p class="sec-sub">{{OPT_SUB}}</p>')
one('aria-label="Safari options"', 'aria-label="Options"')
block('<ul class="know">', '</ul>', '<ul class="know">\n{{KNOW}}\n        </ul>')
i = t.index('<section class="block faq" id="faq">'); j = t.index('</section>', i)
t = t[:i] + '<section class="block faq" id="faq">\n        <h2 class="sec">Questions</h2>\n{{FAQ_HTML}}\n      ' + t[j:]
i = t.index('<section class="block" id="more">'); j = t.index('</section>', i)
t = t[:i] + '<section class="block" id="more">\n        <h2 class="sec">More to do</h2>\n        <p class="sec-sub">{{RELATED_SUB}}</p>\n        <div class="related">\n{{RELATED}}\n        </div>\n      ' + t[j:]
block('<div class="photos-grid">', '</div>', '<div class="photos-grid">\n{{PHOTOS}}\n  </div>')

# booking: no online checkout until our own exists, so WhatsApp and phone only
t = re.sub(r'\n\s*<a class="btn btn-line btn-block" id="book-online"[^\n]*', '', t)
one("    $('book-online').href = o.book;\n", '')
one("\"Hi Khat Tourism, I'd like to book a desert safari.\", 'Safari: ' + o.name,", "\"Hi Khat Tourism, I'd like to book a private tour.\", 'Tour: ' + o.name,")
one("lead_source: 'safari_landing'", "lead_source: '{{SLUG}}'")
one("var p = { safari: state.option.id,", "var p = { tour: state.option.id,")
i = t.index('  var DAY = {'); j = t.index('  };', i) + 4
t = t[:i] + '  var DAY = {{DAY}};' + t[j:]
one("$('price-unit').textContent = o.privateUnit || 'per Land Cruiser';", "$('price-unit').textContent = o.unit;")
one("var price = '<small>From</small><b class=\"num\">' + money(o.private) + '</b><em>' + (o.privateUnit || 'per Land Cruiser') + '</em>';",
    "var price = '<small>From</small><b class=\"num\">' + money(o.private) + '</b><em>' + o.unit + '</em>';")

# assets live in one shared folder for the whole site
t = re.sub(r'(?<=[("\s])(?:\.\./)?img/', '/assets/img/', t)
t = re.sub(r'(?<=[("\s])fonts/', '/assets/fonts/', t)
t = t.replace('/assets/img/logos/', '/assets/img/logos/')

# header navigation (same rules as the homepage)
one('.top-actions { display: flex; align-items: center; gap: 10px; }',
    '.top nav { display: flex; gap: 4px; margin-left: 8px; }\n.top nav a { text-decoration: none; font-weight: 600; font-size: 15px; padding: 8px 12px; border-radius: var(--pill); }\n.top nav a:hover { background: var(--foam); }\n.top nav a[aria-current="page"] { background: var(--sand); }\n.top-actions { margin-left: auto; display: flex; align-items: center; gap: 10px; }\n@media (max-width: 1080px) { .top nav { display: none; } }')
one('.top .wrap { display: flex; align-items: center; justify-content: space-between; gap: 16px; height: 72px; }',
    '.top .wrap { display: flex; align-items: center; gap: 20px; height: 72px; }')

left = sorted(set(re.findall(r'https://khattourism\.com[^"\'\s<)]*', t)))
open(out, 'w').write(t)
print('template written; khattourism.com still referenced (meta/structured data only):', left)
print('tokens:', sorted(set(re.findall(r'\{\{[A-Z_]+\}\}', t))))
